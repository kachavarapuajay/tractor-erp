function docHead(title, no, date, extra) {
  var o = org();
  return '<table class="hdr"><tr><td><div class="org">' + xmlEsc(o.name || '') + '</div>' +
    '<div class="sm">' + xmlEsc(o.address || '') + '</div>' +
    '<div class="sm">GSTIN: ' + xmlEsc(o.gstin || '—') + ' · ' + xmlEsc(stateName(o.stateCode) || '') + '</div>' +
    (o.phone ? '<div class="sm">Ph: ' + xmlEsc(o.phone) + '</div>' : '') + '</td>' +
    '<td class="right"><div class="doctype">' + xmlEsc(title.toUpperCase()) + '</div>' +
    '<div class="strong">' + xmlEsc(no || '') + '</div><div class="sm">' + dmy(date) + '</div>' +
    (extra ? '<div class="sm">' + extra + '</div>' : '') + '</td></tr></table>';
}

function docPartyBox(label, p) {
  return '<div class="box"><div class="sm">' + xmlEsc(label) + '</div><div class="strong">' + xmlEsc(p.name || '') + '</div>' +
    (p.address ? '<div class="sm">' + xmlEsc(p.address) + '</div>' : '') +
    (p.phone ? '<div class="sm">Ph: ' + xmlEsc(p.phone) + '</div>' : '') +
    (p.gstin ? '<div class="sm">GSTIN: ' + xmlEsc(p.gstin) + '</div>' : '') + '</div>';
}

function docPage(title, inner) {
  return '<div class="sheet"><div class="pagetitle">' + xmlEsc(title) + '</div>' + inner +
    '<div class="foot">Generated by Tractor ERP · ' + dmy(today()) + '</div></div>';
}

